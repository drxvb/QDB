//! Deterministic three-path dataset and bit-exact pre-change output comparisons.
use quickdb_api::*;
use quickdb_native::NativeStore;
use std::collections::HashSet;

pub const N: usize = 12_000;
pub const COLUMNS: [&str; 3] = ["exact", "masked", "lazy"];

pub struct Fixture {
    pub store: NativeStore,
    pub vectors: Vec<(u64, Vec<f32>)>,
    pub replacements: Vec<(u64, Vec<f32>)>,
    pub rng: conformance::Lcg,
}

pub fn build(path: &std::path::Path) -> Fixture {
    let mut s = NativeStore::open(path, &OpenOptions::default()).expect("open");
    s.define_table(&TableDef {
        name: "docs".into(),
        columns: COLUMNS
            .iter()
            .map(|name| ColumnDef {
                name: (*name).into(),
                ty: ColumnType::Int,
                indexed: true,
            })
            .collect(),
    })
    .expect("table");
    s.define_vector_index(&VectorIndexDef {
        name: "emb".into(),
        dim: 16,
        metric: Metric::L2,
        m: 8,
        ef_construction: 40,
    })
    .expect("index");
    let mut rng = conformance::Lcg(0x9185);
    let vectors: Vec<_> = (0..N).map(|id| (id as u64, rng.vector(16))).collect();
    let items: Vec<_> = vectors.iter().map(|(id, v)| (*id, v.as_slice())).collect();
    s.upsert_vectors("emb", &items).expect("vectors");
    // Keep tombstones below compaction's 20% boundary.
    let replacements: Vec<_> = (0..N)
        .step_by(13)
        .map(|id| (id as u64, rng.vector(16)))
        .collect();
    let items: Vec<_> = replacements
        .iter()
        .map(|(id, v)| (*id, v.as_slice()))
        .collect();
    s.upsert_vectors("emb", &items).expect("replace");
    let cap = N + replacements.len();
    let sampled: HashSet<_> = (0..256)
        .map(|i| {
            let position = i * cap / 256;
            if position < N {
                position as u64
            } else {
                ((position - N) * 13) as u64
            }
        })
        .collect();
    let rows: Vec<_> = (0..N + 31)
        .map(|id| Row {
            id: id as u64,
            values: vec![
                Value::Int(i64::from(id < 300 && !sampled.contains(&(id as u64)))),
                Value::Int(i64::from(id % 10 < 3 && !sampled.contains(&(id as u64)))),
                Value::Int(i64::from(id % 10 != 9)),
            ],
        })
        .collect();
    s.upsert_rows("docs", &rows).expect("rows");
    let deleted: Vec<_> = (400..N).step_by(97).map(|id| id as u64).collect();
    s.delete_rows("docs", &deleted).expect("delete rows");
    Fixture {
        store: s,
        vectors,
        replacements,
        rng,
    }
}

#[cfg(test)]
mod expected {
    include!("bound_expected.rs");
}

#[test]
fn filtered_matches_old_ids_and_distance_bits_on_all_three_paths() {
    // Generated by bound_reference's frozen collect-all algorithm, not by the new call.
    let dir = tempfile::tempdir().expect("directory");
    let mut fixture = build(dir.path());
    // The vectors are retained for the separate oracle generator, not this comparison.
    assert_eq!(fixture.vectors.len(), N);
    assert_eq!(fixture.replacements.len(), N.div_ceil(13));
    let mut counts = [0; 3];
    for qi in 0..200 {
        let query = fixture.rng.vector(16);
        let (k, ef) = [(1, 8), (7, 32), (17, 64), (31, 128)][qi % 4];
        for (path, column) in COLUMNS.iter().enumerate() {
            let actual = fixture
                .store
                .knn_filtered(
                    "emb",
                    &query,
                    k,
                    ef,
                    "docs",
                    &Filter::Eq {
                        column: (*column).into(),
                        value: Value::Int(1),
                    },
                )
                .expect("KNN");
            let bits: Vec<_> = actual
                .iter()
                .map(|hit| (hit.id, hit.distance.to_bits()))
                .collect();
            assert_eq!(
                bits,
                expected::EXPECTED[qi * 3 + path],
                "query={qi} path={column}"
            );
            counts[path] += 1;
        }
    }
    assert_eq!(counts, [200, 200, 200]);
    println!(
        "BOUND KNN queries=600 exact={} masked={} lazy={} identical_ids_and_distance_bits=true",
        counts[0], counts[1], counts[2]
    );
}
